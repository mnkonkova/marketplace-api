-- Четвёртый вид проекта: «бренд под ключ».
--
-- Это creators_turnkey минус креаторы: выкладки, площадки, ежедневный
-- сбор, отчёт и календарь остаются, а состава, проверки роликов,
-- чек-листов и начислений по людям у него нет — ролики выходят с
-- аккаунтов бренда, и поручать их некому.
--
-- Имя выбрано по тому, что отличает вид физически: аккаунты брендовые.
-- Переписать смысл production_turnkey было нельзя — это умолчание у
-- всех существующих проектов (00032:34) и у всех новых
-- (projects/service.go), плюс на нём висит CHECK про обязательную
-- воронку (00040:12), а у проекта без креаторов воронки нет.
--
-- Отдельной миграцией и с NO TRANSACTION — не из осторожности, а по
-- правилу Postgres: новое значение ENUM нельзя использовать в той же
-- транзакции, в которой оно добавлено, а goose по умолчанию заворачивает
-- миграцию в транзакцию. Любой предикат kind = 'brand_turnkey' рядом с
-- ALTER TYPE даёт «unsafe use of new value of enum type» прямо на
-- выкатке.
ALTER TYPE project_kind ADD VALUE IF NOT EXISTS 'brand_turnkey';


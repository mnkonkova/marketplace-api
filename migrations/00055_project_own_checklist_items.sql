-- Пункт, заведённый ПОД ПРОЕКТ, а не скопированный из библиотеки.
--
-- Менеджер дополняет чек-лист тем, что касается одного бренда: «шрифт
-- титров — Onest Bold», «на Покровке снимать с 8 до 11». В общую
-- библиотеку это класть неверно — она обслуживает все проекты сразу.
--
-- Зачем отдельная колонка, когда есть source_item_id. Он для этого не
-- годится: при удалении пункта из библиотеки он становится NULL (ON
-- DELETE SET NULL), и скопированный пункт делается неотличим от
-- заведённого руками. Разница же стоит дорого — см. ниже.
--
-- Ради чего всё: повторное подключение шаблона (обновление до новой
-- версии) сносит снимок целиком и кладёт заново. Без этого признака
-- вместе со снимком стирались бы и дополнения менеджера — молча, в
-- момент, когда он всего лишь обновляет версию. Теперь его пункты
-- переживают обновление: они не часть библиотечного снимка.
ALTER TABLE project_checklist_items
    ADD COLUMN added_for_project BOOLEAN NOT NULL DEFAULT FALSE;


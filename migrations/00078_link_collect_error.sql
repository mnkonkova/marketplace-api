-- Почему по ссылке нет цифр.
--
-- Сборщик всегда говорит причину: «метрики отдельных постов для vk пока
-- не поддержаны», «ролик не найден», «Account doesn't exist». Мы её
-- выбрасывали: MarkFailed просто отодвигал следующий обход, и в базе не
-- оставалось ни следа.
--
-- Из-за этого в кабинете три разных положения выглядели одинаково —
-- пустой цифрой: площадка не собирается вовсе, ролик удалён, и ролик
-- живой, но его никто не посмотрел. Первое и второе — наша работа,
-- третье — работа креатора, и путать их нельзя. Первого октября 2026 на
-- этом ушёл целый день разбирательств: у проекта стояли нули, а
-- половина ссылок просто не собиралась по причинам, которые сборщик
-- честно называл каждому обходу.
--
-- Храним текст как пришёл, не свой пересказ: пересказ устаревает молча,
-- когда на той стороне меняется формулировка, а по исходному тексту
-- всегда понятно, что именно ответили.
ALTER TABLE publication_links
    ADD COLUMN IF NOT EXISTS last_collect_error TEXT NOT NULL DEFAULT '';

-- Когда в последний раз ПЫТАЛИСЬ собрать. Отдельно от
-- last_collected_at: та говорит «когда цифры получены», эта — «когда
-- ходили». Расхождение между ними и есть «сбор идёт, но не даёт
-- данных», и без второй даты это состояние неотличимо от «сбор не
-- ходил вовсе».
ALTER TABLE publication_links
    ADD COLUMN IF NOT EXISTS last_collect_try_at TIMESTAMPTZ;


-- Фоновый обход стал суточным для всех ссылок.
--
-- Лестницы по возрасту ролика (1→2→4→8 дней) больше нет — решение
-- владельца от 2 октября 2026: «каждый день, если дольше 12 часов не
-- заходили». Без этой миграции правило осталось бы только для НОВЫХ
-- ссылок: шаг лежит в самой строке (collect_every), и у роликов, которые
-- успели дорасти до восьмидневного шага, он таким и остался бы навсегда.
--
-- Минутный шаг не трогаем. Его ставит сдача ссылки, чтобы первый замер
-- не ждал до часа («выложил, а в кабинете ноль»), и до первого удачного
-- обхода он должен дожить. Дальше обход сам запишет сутки.
UPDATE publication_links
SET collect_every = interval '1 day'
WHERE collect_every > interval '1 day';

-- next_collect_at у дорогих ссылок тоже подтягиваем: шаг уменьшился, а
-- срок следующего обхода остался рассчитанным по прежнему. Иначе ролик с
-- восьмидневным шагом впервые пошёл бы по новому правилу через восемь
-- дней, и всё это время «каждый день» было бы обещанием, а не фактом.
--
-- Снятые с обхода не трогаем: 'infinity' — это решение подытога и
-- схлопывания, а не расписание.
UPDATE publication_links
SET next_collect_at = LEAST(next_collect_at, now() + interval '1 day')
WHERE next_collect_at <> 'infinity'::timestamptz
  AND next_collect_at > now() + interval '1 day';


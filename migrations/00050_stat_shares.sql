-- Репосты.
--
-- Сборщик присылает их на каждом обходе (PostMetrics.Shares) и до сих
-- пор выбрасывал: колонки под них не было. А вовлечённость считается
-- как (лайки + комментарии + репосты) ÷ просмотры, и без репостов она
-- занижена.
--
-- NULL означает «площадка их не отдала», и это НЕ ноль: ноль репостов —
-- полноценный ответ, а неизвестность подставлять нулём значит занижать
-- молча. Разница видна снаружи: у показателя, посчитанного без репостов,
-- поднимается признак er_without_shares.
--
-- Прошлое не пересчитывается: у собранных до этой правки строк репостов
-- нет и взять их неоткуда. Их вовлечённость так и останется без
-- репостов — со звёздочкой, но честной. Задним числом подставить
-- сегодняшние репосты к вчерашним просмотрам значило бы нарисовать на
-- графике скачок, которого не было.
ALTER TABLE video_stat_daily
    ADD COLUMN shares BIGINT;

-- Срез периода тоже носит репосты: подытоженный период обязан уметь
-- показать свою вовлечённость теми же числами, что были на отсечку.
ALTER TABLE project_period_views
    ADD COLUMN shares BIGINT;


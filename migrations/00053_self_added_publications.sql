-- Выкладка, которую креатор завёл себе сам.
--
-- Появилась ради простого случая: план периода выполнен, а до ступени не
-- хватает просмотров — пусть добавит ролик и доберёт. Согласования нет
-- намеренно: смысл кнопки в том, чтобы человек мог это сделать сам.
--
-- Признак нужен ровно для одного, и это НЕ отчётность. Недосдача
-- считается как «оклад × (сколько вышло − сколько сдано) ÷ сколько
-- вышло», и если самодобавленные попадут в знаменатель, кнопка начнёт
-- работать против того, кто её нажал: добавил пять роликов, сдал два —
-- и потерял часть оклада за три, которых ему никто не поручал.
--
-- Поэтому в знаменателе недосдачи участвуют только выкладки, которые
-- поставил менеджер. В просмотры, ступени, бонус и статистику
-- самодобавленные идут наравне: просмотры есть просмотры.
ALTER TABLE project_publications
    ADD COLUMN self_added BOOLEAN NOT NULL DEFAULT FALSE;

-- То же самое в срезе подытоженного периода. Именно копией, а не
-- join'ом к живой таблице: срез обязан остаться верным, даже если
-- выкладку потом удалят, — по этой же причине в нём лежат и статус, и
-- дата выхода.
ALTER TABLE project_period_publications
    ADD COLUMN self_added BOOLEAN NOT NULL DEFAULT FALSE;


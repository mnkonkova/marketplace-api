-- Название ролика.
--
-- Тему выкладки задаёт дата — по ней проект и ведут. Но когда ролик уже
-- вышел, дата перестаёт что-либо значить: в отчёте и в ленте заказчика
-- двенадцать строк «Выкладка 07», и понять, какая из них про распаковку,
-- а какая про сравнение с конкурентом, нельзя ни менеджеру, ни клиенту.
-- Название пишет креатор в момент сдачи: он единственный, кто знает, что
-- снял.
--
-- Пусто — допустимо: у запланированных выкладок названия ещё нет, а
-- сданные раньше этой миграции его не получат задним числом.
ALTER TABLE project_publications
    ADD COLUMN title TEXT NOT NULL DEFAULT '';

-- +goose Down
ALTER TABLE project_publications
    DROP COLUMN IF EXISTS title;

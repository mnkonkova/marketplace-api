-- Снимки подписчиков аккаунта по дням.
--
-- Доплата за подписчиков считается с ПРИРОСТА за период, а площадки
-- отдают только «сколько сейчас». Без истории прирост не отличить от
-- того, что человек набрал до проекта: менеджер вписывал число руками,
-- и проверить его было нечем.
--
-- Устроено ровно как video_stat_daily: накопительный снимок на день, по
-- одной строке на аккаунт. Прирост за период — разница крайних снимков,
-- а не сумма дневных дельт: пропущенный день тогда ничего не ломает, а
-- при суммировании он терялся бы навсегда.
--
-- Почему не «срез на открытии периода и на закрытии» отдельной таблицей
-- с двумя рёбрами: аккаунт прикрепляют посреди периода, и тогда
-- открывающего среза у него нет вовсе. С историей по дням этот случай
-- решается сам — первый снимок появляется в день прикрепления, и
-- прирост считается от него. Решение владельца от 2 октября: «снимать
-- снимок аков с этого момента — виноваты оба».
CREATE TABLE account_follower_daily (
    account_id UUID NOT NULL REFERENCES project_accounts (id) ON DELETE CASCADE,
    -- stat_date — день снимка по UTC, как у video_stat_daily.
    stat_date DATE NOT NULL,
    -- followers — сколько подписчиков у аккаунта НА ЭТОТ ДЕНЬ, а не
    -- прибавилось за день.
    followers BIGINT NOT NULL CHECK (followers >= 0),
    -- taken_at — когда именно сходили. Нужен для разбора «почему здесь
    -- вчерашнее число»: обход идёт раз в сутки на аккаунт, и время
    -- внутри дня у разных аккаунтов разное.
    taken_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (account_id, stat_date)
);

COMMENT ON TABLE account_follower_daily IS
    'Снимки числа подписчиков аккаунта по дням; прирост за период — разница крайних снимков';


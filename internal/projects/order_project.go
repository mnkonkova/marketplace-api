package projects

import (
	"context"
	"fmt"

	"github.com/google/uuid"
)

// Проект заявки «под ключ»: заводится в момент отправки, до ответов
// креаторов.
//
// Раньше проект появлялся ПОСЛЕ оплаты, и до этого момента у заказчика
// не было ничего — ни страницы, ни переписки. Человек нажимал
// «Отправить», читал «мы вам напишем» и уходил в тишину на несколько
// дней, пока менеджер звонит и считает. Теперь ему есть куда прийти:
// проект виден в кабинете, в нём работает переписка (её событие идёт в
// общий чат даже без назначенного менеджера), к нему цепляются тариф,
// чеклист и даты выкладок — всё, что менеджер правит на шаге «начинает
// подсчёт».
//
// Отдельным файлом и простыми параметрами: пакет orders объявляет этот
// интерфейс у себя, а общий DTO замкнул бы импорты в кольцо.

// StartOrderProject — завести проект под заявку.
//
// Статус получается active — его ставит INSERT репозитория, и это
// правильно: «висящий» проект отличается от работающего не статусом, а
// пустым составом, и показать надо именно это. Отдельный draft пришлось
// бы пускать в кабинет, в списки менеджера и в сводки руками — то есть
// завести второй способ сказать «ещё не собрано».
func (s *Service) StartOrderProject(
	ctx context.Context, clientID uuid.UUID, title, notes string, monthlyPlan int,
) (uuid.UUID, error) {
	// monthlyPlan приходит из заявки, но в проект пока не пишется:
	// колонка monthly_plan заполняется менеджером на финализации вместе
	// с датами выкладок. Держим параметр в подписи, чтобы не менять её
	// на том шаге, и чтобы было видно: число известно уже сейчас.
	_ = monthlyPlan
	in := StartProjectInput{
		ClientUserID: &clientID,
		Title:        title,
		Notes:        notes,
		Kind:         KindCreatorsTurnkey,
		// Источник — маркетплейс: проект пришёл заявкой из кабинета, а не
		// заведён менеджером руками. По этому полю потом считают, откуда
		// идёт работа.
		Source: SourceMarketplace,
	}
	id, err := s.StartProject(ctx, in)
	if err != nil {
		return uuid.Nil, fmt.Errorf("start order project: %w", err)
	}
	return id, nil
}

// CancelOrderProject — компенсация: заявка не записалась, проект уже
// есть. Отменённый проект кабинет заказчика не показывает
// (ListForClient прячет cancelled), и пустая карточка не мозолит глаза.
//
// Отменяем от имени самого заказчика: действие сделано по его запросу,
// и «отменил неизвестно кто» в истории проекта читается хуже.
func (s *Service) CancelOrderProject(ctx context.Context, projectID, clientID uuid.UUID) error {
	return s.repo.CancelProject(ctx, projectID, clientID,
		"заявка не записалась — проект отменён автоматически")
}

// UpdateProjectNotes — переписать заметки проекта брифом заявки.
//
// Заметки — то место, где менеджер читает бриф: отдельного экрана под
// него нет, и заводить второй источник правды о том же тексте значит
// однажды показать старую версию.
func (s *Service) UpdateProjectNotes(ctx context.Context, projectID uuid.UUID, notes string) error {
	// Через тот же PatchProject, которым правит менеджер: своя строчка
	// UPDATE рядом с ним разошлась бы с ним на первой же новой колонке
	// (например, когда заметки начнут писаться в историю проекта).
	_, err := s.repo.PatchProject(ctx, projectID, ManagerPatchInput{Notes: &notes})
	return err
}

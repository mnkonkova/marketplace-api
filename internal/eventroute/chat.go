package eventroute

import "sort"

// Таблица назначения событий: что уходит в общий чат, а что нет.
//
// Зачем она вообще. Приложение шлёт в CRM-вебхук почти сорок типов
// событий, а workflow в n8n разбирает горстку: остальное попадает в
// ветку default, которая возвращает пусто и отвечает нам 200. Воркер
// считает доставку успешной, метрики чистые, ошибок нет — и никто не
// узнаёт, что сводка менеджерам и напоминания о выкладках честно
// считаются, дедуплицируются и выбрасываются.
//
// Поэтому решение «идёт / не идёт» объявлено здесь явно для каждого
// типа, а тесты не дают ни завести тип мимо таблицы, ни разойтись
// таблице с самим workflow.
//
// ПРИНЦИП, по которому делить (следующий человек должен решать так же):
//
//	в чат идёт только то, на что нужно ответить человеком и чего он
//	иначе не увидит вовремя.
//
// Остальное живёт в CRM: там есть сводка «Требует внимания», и
// дублировать её в чат — значит превратить чат в ленту, которую
// перестанут читать. Сомневаешься — CRMOnly: пропущенный в чате пункт
// виден в сводке, а лишний шум не виден никак, он просто убивает
// внимание к остальным сообщениям.
type Delivery int

const (
	// ToChat — событие рендерится в сообщение и уходит в общий чат.
	ToChat Delivery = iota + 1
	// CRMOnly — намеренно не идёт в чат. Не «забыли»: строка в таблице
	// и есть решение.
	CRMOnly
)

// chatRouting — назначение каждого типа событий CRM-вебхука и
// поддержки. Свободных типов быть не должно: тест сверяет таблицу с
// тем, что код умеет emit'ить.
var chatRouting = map[string]Delivery{
	// ── Проект: заведение и ответственный ──────────────────────────
	// Новый бриф: пока его никто не взял, работа не идёт.
	"project.created": ToChat,
	// Разовый заказ: то же самое, только другим путём — его надо взять.
	"project.general_created": ToChat,
	// Менеджер взял проект — виден ответ на «кто это делает».
	"project.assigned": ToChat,
	// Снятие ответственного в чат не идёт, и это решение принято —
	// не пересматривайте заново. Проект остаётся без менеджера не сам
	// по себе: админ минуту назад снял роль или передал дела, то есть
	// человек, которому надо знать, — это тот, кто нажал кнопку. Тем и
	// отличается от project.created: бриф приходит снаружи и тогда,
	// когда в CRM никто не смотрит.
	"project.unassigned": CRMOnly,

	// ── Проект: исполнитель ────────────────────────────────────────
	// Клиент выбрал специалиста — ждём решения менеджера.
	"project.specialist_assigned": ToChat,
	// Менеджер подтвердил.
	"project.specialist_approved": ToChat,
	// Менеджер отклонил. Без этого чат рассказывал половину истории:
	// «клиент выбрал», «менеджер подтвердил» — и тишина там, где
	// подтверждения не будет.
	"project.specialist_rejected": ToChat,

	// ── Проект: разговор и споры ───────────────────────────────────
	// Комментарий: на него отвечают словами, и в CRM его увидят
	// только те, кто туда зайдёт.
	"project.comment_added": ToChat,
	// Спор с клиентом — отвечают человеком и срочно.
	"project.disputed": ToChat,

	// ── Проект: движение по воронке ────────────────────────────────
	// Всё это — рабочий ход проекта. Отвечать не на что, а поток
	// сообщений на каждый шаг заглушил бы то, на что отвечать надо.
	"project.step_transitioned": CRMOnly,
	"project.stage_advanced":    CRMOnly,
	"project.stage_moved":       CRMOnly,
	"project.step_moved":        CRMOnly,
	"project.funnel_changed":    CRMOnly,
	"project.completed":         CRMOnly,
	"project.cancelled":         CRMOnly,
	"project.restored":          CRMOnly,

	// ── Выкладки ───────────────────────────────────────────────────
	// План выставлен, ролик сдан, неполная выкладка закрыта руками —
	// это отчётность, её место в проекте.
	"project.publications_created":  CRMOnly,
	"project.publication_submitted": CRMOnly,
	"project.publication_closed":    CRMOnly,
	// Правка ссылки менеджером — CRMOnly: это внутренняя починка
	// данных, а не повод отвечать человеком. В карточке выкладки она
	// видна, в истории проекта записана.
	"project.publication_link_edited": CRMOnly,
	// Напоминания креатору лично: «сегодня срок» и «вышло не везде» —
	// его дело, чат менеджеров они бы только засыпали.
	"project.publication_due_today":  CRMOnly,
	"project.publication_incomplete": CRMOnly,
	// Ручное напоминание менеджера: он его сам и отправил.
	"project.publication_manual": CRMOnly,
	// А вот просрочка — уже срыв срока, тут нужен человек.
	"project.publication_overdue": ToChat,
	// Сводка менеджерам ровно для чата и задумана: она и есть
	// «что горит сегодня».
	"project.manager_digest": ToChat,
	// Период подытожен: просмотры заморожены, счёт посчитан. Это
	// единственный момент, когда по периоду становится что обсуждать, и
	// происходит он сам — человек об этом иначе не узнает вовремя.
	"project.period_closed": ToChat,

	// ── Разовые заказы ─────────────────────────────────────────────
	// Сдача, приёмка, доработка и отмена разового заказа — переписка
	// клиента с исполнителем внутри CRM.
	"project.general_delivered": CRMOnly,
	"project.general_accepted":  CRMOnly,
	"project.general_rework":    CRMOnly,
	"project.general_cancelled": CRMOnly,

	// ── Подбор креаторов ───────────────────────────────────────────
	// Ход подбора: приглашения и ответы на них. Пока машина справляется
	// сама, человеку смотреть не на что.
	"order.invitation_sent":     CRMOnly,
	"order.invitation_accepted": CRMOnly,
	"order.invitation_declined": CRMOnly,
	"order.invitation_expired":  CRMOnly,
	"order.staffed":             CRMOnly,
	// Резерв кончился, состав не собран — дальше без человека никак.
	"order.need_more": ToChat,
	// Приглашённый молчит сутки: место занято и не двигается.
	"order.candidate_silent": ToChat,

	// ── Модерация ──────────────────────────────────────────────────
	// Специалист ждёт решения о публикации — обещанный срок сутки.
	"moderation.specialist_pending": ToChat,

	// ── Поддержка ──────────────────────────────────────────────────
	// Обращение из футера. Идёт в чат, но своим workflow (crmSupport):
	// у него отдельный вебхук, дамп в Telegram и письмо на info@.
	"support.message_received": ToChat,
}

// DeliveryOf — назначение типа события. ok=false означает, что тип в
// таблице не объявлен: это не «не идёт в чат», а «решение не принято».
func DeliveryOf(eventType string) (Delivery, bool) {
	d, ok := chatRouting[eventType]
	return d, ok
}

// ChatEvents — типы, которые должны попадать в чат, по алфавиту.
// Ими же сверяется workflow в n8n.
func ChatEvents() []string {
	out := make([]string, 0, len(chatRouting))
	for t, d := range chatRouting {
		if d == ToChat {
			out = append(out, t)
		}
	}
	sort.Strings(out)
	return out
}

// KnownEvents — все объявленные типы, по алфавиту.
func KnownEvents() []string {
	out := make([]string, 0, len(chatRouting))
	for t := range chatRouting {
		out = append(out, t)
	}
	sort.Strings(out)
	return out
}
